const express = require('express');
const router = express.Router();
const DataEngine = require('../engine/dataEngine');
router.get('/training-stats', (req, res) => {
    res.json(DataEngine.generateMLUpdate());
});
router.get('/training-history', (req, res) => {
    const { rand } = DataEngine;
    const points = parseInt(req.query.points) || 80;
    const loss = [], accuracy = [];
    for (let i = 0; i < points; i++) {
        const t = i / points;
        loss.push(parseFloat((Math.max(0.01, 1 - 0.97 * (1 - Math.exp(-5 * t)) + rand(-0.01, 0.01))).toFixed(4)));
        accuracy.push(parseFloat((Math.min(1, 0.97 * (1 - Math.exp(-5 * t)) + rand(-0.005, 0.005))).toFixed(4)));
    }
    res.json({ loss, accuracy, points, timestamp: DataEngine.nowISO() });
});
router.get('/inference-log', (req, res) => {
    const limit = Math.min(parseInt(req.query.limit) || 30, 100);
    for (let i = 0; i < 3; i++) DataEngine.STATE.mlInferenceLog.unshift(DataEngine.generateMLInferenceEntry());
    if (DataEngine.STATE.mlInferenceLog.length > 200) DataEngine.STATE.mlInferenceLog.length = 200;
    res.json({ items: DataEngine.STATE.mlInferenceLog.slice(0, limit), total: DataEngine.STATE.mlInferenceLog.length, timestamp: DataEngine.nowISO() });
});
router.get('/inference-log/live', (req, res) => {
    const entry = DataEngine.generateMLInferenceEntry();
    DataEngine.STATE.mlInferenceLog.unshift(entry);
    res.json(entry);
});
router.get('/confusion-matrix', (req, res) => {
    const labels = ['Normal', 'BruteForce', 'DDoS', 'Malware', 'SQLi', 'Phish'];
    const matrix = labels.map((_, r) =>
        labels.map((_, c) => parseFloat((r === c ? DataEngine.rand(0.85, 0.98) : DataEngine.rand(0, 0.08)).toFixed(4)))
    );
    res.json({ labels, matrix, timestamp: DataEngine.nowISO() });
});
router.get('/feature-weights', (req, res) => {
    const { rand } = DataEngine;
    res.json({
        features: [
            { name: 'Payload Entropy', weight: parseFloat((0.34 + rand(-0.02, 0.02)).toFixed(3)), color: 'pink' },
            { name: 'Req Frequency', weight: parseFloat((0.28 + rand(-0.02, 0.02)).toFixed(3)), color: 'purple' },
            { name: 'Geo Bias', weight: parseFloat((0.15 + rand(-0.01, 0.01)).toFixed(3)), color: 'cyan' },
            { name: 'Protocol Anomaly', weight: parseFloat((0.12 + rand(-0.01, 0.01)).toFixed(3)), color: 'orange' },
            { name: 'Time Distribution', weight: parseFloat((0.11 + rand(-0.01, 0.01)).toFixed(3)), color: 'green' },
        ],
        modelVersion: 'LSTM-v3',
        timestamp: DataEngine.nowISO()
    });
});
router.post('/generate-report', (req, res) => {
    const stats = DataEngine.generateMLUpdate();
    const md = [
        `# AEGIS Machine Learning Engine - Auto-Training Report`,
        `Generated: ${DataEngine.nowISO()}`,
        ``,
        `## Model Performance`,
        `- Epochs Completed: ${stats.epochs}`,
        `- Current Loss: ${stats.loss}`,
        `- Validation Accuracy: ${stats.valAccuracy}%`,
        `- F1 Score: ${stats.f1Score}`,
        ``,
        `## Sub-Network Status`,
        `- Learning & Audit Agent: ONLINE`,
        `- Threat Model Status: EVOLVING`,
        `- Latest Checkpoint: SAVED`,
        ``,
        `*Report automatically generated by AEGIS Head Agent.*`
    ].join('\n');
    res.json({ success: true, report: { title: 'AEGIS ML Report', generatedAt: stats.timestamp, stats, markdown: md } });
});
